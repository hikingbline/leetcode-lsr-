//技巧问题(双指针)
//98 颜色分类
// 给定一个包含红色、白色和蓝色、共 n 个元素的数组 nums ，原地 对它们进行排序，
// 使得相同颜色的元素相邻，并按照红色、白色、蓝色顺序排列。
// 我们使用整数 0、 1 和 2 分别表示红色、白色和蓝色。
// 必须在不使用库内置的 sort 函数的情况下解决这个问题。

/**
 * 对包含0、1、2三种元素的数组进行排序，使得0在最前面，1在中间，2在最后面
 * 采用双指针法，时间复杂度O(n)，空间复杂度O(1)
 * @param {number[]} nums - 待排序的数组（仅包含0、1、2）
 * @return {void} 不返回任何值，直接在原数组上修改
 */
var sortColors = function(nums) {
    // left指针：指向0的右边界（即left左侧元素均为0），初始化为0
    let left = 0;
    // right指针：指向2的左边界（即right右侧元素均为2），初始化为数组最后一位索引
    let right = nums.length - 1;
    // i指针：用于遍历数组，寻找需要交换的元素
    let i = 0;

    // 遍历终止条件：i超过right时，说明所有元素已处理完毕
    while (i <= right) {
        // 当当前元素为2时，将其交换到right位置（2的正确区域）
        // 使用while循环处理连续的2，确保交换后当前位置不是2
        while (i <= right && nums[i] === 2) {
            // 交换i和right位置的元素
            [nums[i], nums[right]] = [nums[right], nums[i]];
            // right左移，缩小2的区域范围
            right--;
        }

        // 当当前元素为0时，将其交换到left位置（0的正确区域）
        if (nums[i] === 0) {
            // 交换i和left位置的元素
            [nums[i], nums[left]] = [nums[left], nums[i]];
            // left右移，扩大0的区域范围
            left++;
        }

        // 处理完当前元素后，i右移继续遍历
        i++;
    }
};
