//双指针问题
//5.盛最多水的容器
// 给定一个长度为 n 的整数数组 height 。有 n 条垂线，第 i 条线的两个端点是 (i, 0) 和 (i, height[i]) 。
// 找出其中的两条线，使得它们与 x 轴共同构成的容器可以容纳最多的水。
// 返回容器可以储存的最大水量

/**
 * 计算由数组中两条垂线与x轴构成的容器能容纳的最大水量
 * @param {number[]} height - 存储各位置垂线高度的数组，下标表示x轴位置，值表示垂线高度
 * @return {number} - 返回能容纳的最大水量
 */
// 采用双指针解法：通过左右指针向中间移动，高效寻找最大面积
var maxArea = function (height) {
  // 左指针初始化为数组起始位置（最左端）
  let left = 0;
  // 右指针初始化为数组结束位置（最右端）
  let right = height.length - 1;
  // 用于存储最大面积的变量，初始化为0
  let ans = 0;

  // 当左右指针未相遇时，继续循环计算
  while (right > left) {
    // 计算当前左右指针所指垂线构成的容器面积
    // 面积 = 两垂线之间的水平距离（right - left） * 两垂线中较矮的高度（决定水位上限）
    let area = (right - left) * Math.min(height[right], height[left]);
    // 更新最大面积：取当前面积与历史最大面积中的较大值
    ans = Math.max(area, ans);

    // 移动指针策略：为了可能获得更大面积，移动较矮的垂线指针
    // 因为若移动较高的垂线，水平距离减小，而高度上限由较矮的决定，面积只会更小
    if (height[left] > height[right]) {
      // 右指针所指垂线较矮，右指针左移
      right--;
    } else {
      // 左指针所指垂线较矮（或等高），左指针右移
      left++;
    }
  }

  // 循环结束后，返回最大面积
  return ans;
};